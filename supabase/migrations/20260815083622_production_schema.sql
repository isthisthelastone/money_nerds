left join lateral (
  select coalesce(sum(d.lamports), 0)::bigint as received_lamports
  from public.donations d where d.recipient_wallet = pr.wallet_address
) vr on true
left join lateral (
  select coalesce(sum(d.amount_lamports), 0)::bigint as sent_lamports
  from public.legacy_unverified_donations d where d.donor_wallet = pr.wallet_address
) ls on true
