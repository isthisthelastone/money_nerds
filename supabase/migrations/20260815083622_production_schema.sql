-- Timestamp, hierarchy, media ownership, aggregate, and donation integrity helpers.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end
$$;

create or replace function public.validate_comment_parent()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_post_id bigint;
  parent_depth smallint;
begin
  if new.parent_id is null then
    new.depth := 0;
    return new;
  end if;

  if new.id is not null and new.parent_id = new.id then
    raise exception 'A comment cannot reply to itself';
  end if;

  select c.post_id, c.depth
  into parent_post_id, parent_depth
  from public.comments c
  where c.id = new.parent_id;

  if not found then
    raise exception 'Parent comment does not exist';
  end if;
  if parent_post_id <> new.post_id then
    raise exception 'Parent comment belongs to another post';
  end if;
  if parent_depth >= 5 then
    raise exception 'Maximum reply depth is 5';
  end if;

  new.depth := parent_depth + 1;
  return new;
end
$$;

create or replace function public.sync_post_comment_count()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    update public.posts set comment_count = comment_count + 1 where id = new.post_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.posts set comment_count = greatest(comment_count - 1, 0) where id = old.post_id;
    return old;
  elsif old.post_id is distinct from new.post_id then
    update public.posts set comment_count = greatest(comment_count - 1, 0) where id = old.post_id;
    update public.posts set comment_count = comment_count + 1 where id = new.post_id;
  end if;
  return new;
end
$$;

create or replace function public.validate_media_owner()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  asset_owner text;
  content_owner text;
begin
  select m.owner_wallet into asset_owner
  from public.media_assets m where m.id = new.media_id;

  if tg_table_name = 'post_media' then
    select p.author_wallet into content_owner
    from public.posts p where p.id = new.post_id;
  else
    select c.author_wallet into content_owner
    from public.comments c where c.id = new.comment_id;
  end if;

  if content_owner is null or asset_owner <> content_owner then
    raise exception 'Media owner must match content author';
  end if;
  return new;
end
$$;

create or replace function public.validate_verified_donation_target()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  expected_recipient text;
begin
  if new.target_type = 'post' then
    select p.author_wallet into expected_recipient from public.posts p where p.id = new.post_id;
  elsif new.target_type = 'comment' then
    select c.author_wallet into expected_recipient from public.comments c where c.id = new.comment_id;
  else
    -- The service wallet is configured and verified by the server route.
    return new;
  end if;

  if expected_recipient is null then
    raise exception 'Donation target has no valid recipient wallet';
  end if;
  if new.recipient_wallet <> expected_recipient then
    raise exception 'Verified transfer recipient does not match content recipient';
  end if;
  return new;
end
$$;

create or replace function public.sync_verified_donation_totals()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.target_type = 'post' then
      update public.posts
      set verified_donation_lamports = verified_donation_lamports + new.lamports
      where id = new.post_id;
    elsif new.target_type = 'comment' then
      update public.comments
      set verified_donation_lamports = verified_donation_lamports + new.lamports
      where id = new.comment_id;
    end if;
    return new;
  end if;

  if old.target_type = 'post' then
    update public.posts
    set verified_donation_lamports = greatest(verified_donation_lamports - old.lamports, 0)
    where id = old.post_id;
  elsif old.target_type = 'comment' then
    update public.comments
    set verified_donation_lamports = greatest(verified_donation_lamports - old.lamports, 0)
    where id = old.comment_id;
  end if;
  return old;
end
$$;

