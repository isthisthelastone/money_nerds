create table if not exists public.post_likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  wallet_address text not null references public.profiles(wallet_address)
    on update cascade on delete restrict,
  created_at timestamptz not null default now(),
  primary key (post_id, wallet_address)
);

create table if not exists public.comment_likes (
  comment_id bigint not null references public.comments(id) on delete cascade,
  wallet_address text not null references public.profiles(wallet_address)
    on update cascade on delete restrict,
  created_at timestamptz not null default now(),
  primary key (comment_id, wallet_address)
);

insert into public.post_likes (post_id, wallet_address, created_at)
select pi.id, btrim(l.wallet_address), pi.created_at
from public.post_info pi
join public.posts p on p.id = pi.id
cross join lateral unnest(coalesce(pi.liked_by, array[]::text[])) as l(wallet_address)
join public.profiles pr on pr.wallet_address = btrim(l.wallet_address)
where btrim(coalesce(l.wallet_address, '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
group by pi.id, btrim(l.wallet_address), pi.created_at
on conflict (post_id, wallet_address) do nothing;

insert into public.comment_likes (comment_id, wallet_address, created_at)
select c.id, btrim(l.wallet_address), c.created_at
from public.comments c
cross join lateral unnest(coalesce(c.likes, array[]::text[])) as l(wallet_address)
join public.profiles pr on pr.wallet_address = btrim(l.wallet_address)
where btrim(coalesce(l.wallet_address, '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
group by c.id, btrim(l.wallet_address), c.created_at
on conflict (comment_id, wallet_address) do nothing;

with exact_likes as (
  select p.id, count(pl.wallet_address)::bigint as exact_count
  from public.posts p
  left join public.post_likes pl on pl.post_id = p.id
  group by p.id
)
update public.posts p
set legacy_unattributed_like_count = greatest(coalesce(p.likes, 0) - e.exact_count, 0),
    like_count = e.exact_count
from exact_likes e
where e.id = p.id;

update public.comments c
set like_count = x.exact_count
from (
  select c2.id, count(cl.wallet_address)::bigint as exact_count
  from public.comments c2
  left join public.comment_likes cl on cl.comment_id = c2.id
  group by c2.id
) x
where x.id = c.id;

-- New donations are inserted only after a trusted server verifies the Solana
-- transaction. A transaction instruction may be recorded once globally.
create table if not exists public.donations (
  signature text primary key,
  network text not null default 'mainnet-beta',
  instruction_index integer not null default 0,
  donor_wallet text not null references public.profiles(wallet_address)
    on update cascade on delete restrict,
  recipient_wallet text not null,
  target_type text not null,
  post_id bigint references public.posts(id) on delete cascade,
  comment_id bigint references public.comments(id) on delete cascade,
  lamports bigint not null,
  slot bigint,
  status text not null default 'verified',
  verified_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint donations_target_shape check (
    (target_type = 'post' and post_id is not null and comment_id is null)
    or (target_type = 'comment' and comment_id is not null and post_id is null)
    or (target_type = 'service' and post_id is null and comment_id is null)
  ),
  constraint donations_target_type check (target_type in ('post', 'comment', 'service')),
  constraint donations_amount_positive check (lamports > 0),
  constraint donations_instruction_nonnegative check (instruction_index >= 0),
  constraint donations_network check (network in ('mainnet-beta', 'devnet', 'testnet')),
  constraint donations_status check (status = 'verified'),
  constraint donations_signature_shape check (signature ~ '^[1-9A-HJ-NP-Za-km-z]{80,90}$'),
  constraint donations_recipient_shape check (
    recipient_wallet ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
  )
);

-- Historical JSON donation totals have no transaction signature and therefore
-- must never be presented as verified. raw_amount preserves every original value.
create table if not exists public.legacy_unverified_donations (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  donor_wallet text not null,
  recipient_wallet text not null references public.profiles(wallet_address)
    on update cascade on delete restrict,
  amount_lamports bigint,
  raw_amount jsonb not null,
  source text not null default 'posts.donated',
  migrated_at timestamptz not null default now(),
  constraint legacy_unverified_amount_nonnegative check (
    amount_lamports is null or amount_lamports >= 0
  ),
  unique (post_id, donor_wallet, source)
);

insert into public.legacy_unverified_donations (
  post_id, donor_wallet, recipient_wallet, amount_lamports, raw_amount
)
select
  p.id,
  btrim(d.key),
  p.author_wallet,
  case
    when jsonb_typeof(d.value) = 'number'
      and (d.value #>> '{}')::numeric >= 0
      then round((d.value #>> '{}')::numeric * 1000000000)::bigint
    else null
  end,
  d.value
from public.posts p
cross join lateral jsonb_each(
  case when jsonb_typeof(p.donated) = 'object' then p.donated else '{}'::jsonb end
) as d(key, value)
on conflict (post_id, donor_wallet, source) do update
set amount_lamports = excluded.amount_lamports,
    raw_amount = excluded.raw_amount,
    recipient_wallet = excluded.recipient_wallet;

update public.posts p
set legacy_donation_lamports = x.total_lamports
from (
  select p2.id, coalesce(sum(l.amount_lamports), 0)::bigint as total_lamports
  from public.posts p2
  left join public.legacy_unverified_donations l on l.post_id = p2.id
  group by p2.id
) x
where x.id = p.id;

