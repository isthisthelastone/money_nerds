  migrated_post_likes bigint;
  source_comment_likes bigint;
  migrated_comment_likes bigint;
  expected_total_likes bigint;
  migrated_total_likes bigint;
  source_legacy_donations bigint;
  migrated_legacy_donations bigint;
begin
  select count(*) into source_post_likes
  from (
    select pi.id, btrim(l.wallet_address)
    from public.post_info pi
    join public.posts p on p.id = pi.id
    cross join lateral unnest(coalesce(pi.liked_by, array[]::text[])) as l(wallet_address)
    where btrim(coalesce(l.wallet_address, '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
    group by pi.id, btrim(l.wallet_address)
  ) x;
  select count(*) into migrated_post_likes from public.post_likes;
  if migrated_post_likes <> source_post_likes then
    raise exception 'Post-like reconciliation failed: source %, migrated %',
      source_post_likes, migrated_post_likes;
  end if;

  select count(*) into source_comment_likes
  from (
    select c.id, btrim(l.wallet_address)
    from public.comments c
    cross join lateral unnest(coalesce(c.likes, array[]::text[])) as l(wallet_address)
    where btrim(coalesce(l.wallet_address, '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
    group by c.id, btrim(l.wallet_address)
  ) x;
  select count(*) into migrated_comment_likes from public.comment_likes;
  if migrated_comment_likes <> source_comment_likes then
    raise exception 'Comment-like reconciliation failed: source %, migrated %',
      source_comment_likes, migrated_comment_likes;
  end if;

  select coalesce(sum(greatest(coalesce(p.likes, 0), x.exact_count)), 0)
  into expected_total_likes
  from public.posts p
  join (
    select p2.id, count(pl.wallet_address)::bigint as exact_count
    from public.posts p2 left join public.post_likes pl on pl.post_id = p2.id
    group by p2.id
  ) x on x.id = p.id;
  select coalesce(sum(like_count + legacy_unattributed_like_count), 0)
  into migrated_total_likes from public.posts;
  if migrated_total_likes <> expected_total_likes then
    raise exception 'Like-total reconciliation failed: expected %, migrated %',
      expected_total_likes, migrated_total_likes;
  end if;

  select count(*) into source_legacy_donations
  from public.posts p
  cross join lateral jsonb_each(
    case when jsonb_typeof(p.donated) = 'object' then p.donated else '{}'::jsonb end
  ) d;
  select count(*) into migrated_legacy_donations
  from public.legacy_unverified_donations;
  if migrated_legacy_donations <> source_legacy_donations then
    raise exception 'Legacy donation reconciliation failed: source %, migrated %',
      source_legacy_donations, migrated_legacy_donations;
  end if;
end
