-- Service-only RPC. The target row lock serializes concurrent toggles, while the
-- normalized primary key guarantees one wallet can like a target only once.
create or replace function public.toggle_like_for_wallet(
  p_wallet_address text,
  p_post_id bigint default null,
  p_comment_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  now_liked boolean;
  current_count bigint;
  legacy_count bigint := 0;
begin
  p_wallet_address := btrim(p_wallet_address);
  if p_wallet_address !~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$' then
    raise exception 'Invalid Solana wallet address';
  end if;
  if num_nonnulls(p_post_id, p_comment_id) <> 1 then
    raise exception 'Exactly one of p_post_id or p_comment_id is required';
  end if;
  if not exists (
    select 1 from public.profiles p where p.wallet_address = p_wallet_address
  ) then
    raise exception 'Wallet profile does not exist';
  end if;

  if p_post_id is not null then
    perform 1 from public.posts p where p.id = p_post_id for update;
    if not found then raise exception 'Post does not exist'; end if;

    delete from public.post_likes
    where post_id = p_post_id and wallet_address = p_wallet_address;

    if found then
      now_liked := false;
      update public.posts
      set like_count = greatest(like_count - 1, 0)
      where id = p_post_id
      returning like_count, legacy_unattributed_like_count into current_count, legacy_count;
    else
      insert into public.post_likes (post_id, wallet_address)
      values (p_post_id, p_wallet_address);
      now_liked := true;
      update public.posts set like_count = like_count + 1 where id = p_post_id
      returning like_count, legacy_unattributed_like_count into current_count, legacy_count;
    end if;

    return jsonb_build_object(
      'target', 'post', 'id', p_post_id, 'liked', now_liked,
      'like_count', current_count, 'legacy_like_count', legacy_count,
      'count', current_count + legacy_count
    );
  end if;

  perform 1 from public.comments c where c.id = p_comment_id for update;
  if not found then raise exception 'Comment does not exist'; end if;

  delete from public.comment_likes
  where comment_id = p_comment_id and wallet_address = p_wallet_address;

  if found then
    now_liked := false;
    update public.comments set like_count = greatest(like_count - 1, 0)
    where id = p_comment_id returning like_count into current_count;
  else
    insert into public.comment_likes (comment_id, wallet_address)
    values (p_comment_id, p_wallet_address);
    now_liked := true;
    update public.comments set like_count = like_count + 1
    where id = p_comment_id returning like_count into current_count;
  end if;

  return jsonb_build_object(
    'target', 'comment', 'id', p_comment_id, 'liked', now_liked,
    'like_count', current_count, 'count', current_count
  );
end
$$;

-- Wallet challenge/session RPCs are callable only with the server-side service
-- role. Signature verification remains in the Node route; session establishment
-- atomically consumes the already-verified challenge so it cannot be replayed.
create or replace function public.issue_wallet_challenge(
  p_wallet_address text,
  p_message text,
  p_expires_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  challenge_id uuid;
begin
  p_wallet_address := btrim(p_wallet_address);
  if p_wallet_address !~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$' then
    raise exception 'Invalid Solana wallet address';
  end if;
  if p_expires_at <= now() or p_expires_at > now() + interval '10 minutes' then
    raise exception 'Challenge expiration must be within 10 minutes';
  end if;
  if char_length(p_message) not between 32 and 4096
     or position(p_wallet_address in p_message) = 0 then
    raise exception 'Challenge message is invalid';
  end if;

  insert into public.wallet_challenges (wallet_address, message, expires_at)
  values (p_wallet_address, p_message, p_expires_at)
  returning id into challenge_id;

  return jsonb_build_object(
    'id', challenge_id,
    'wallet_address', p_wallet_address,
    'message', p_message,
    'expires_at', p_expires_at
  );
end
$$;

create or replace function public.establish_wallet_session(
  p_challenge_id uuid,
  p_wallet_address text,
  p_token_hash text,
  p_session_expires_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  consumed_id uuid;
begin
  p_wallet_address := btrim(p_wallet_address);
  p_token_hash := lower(btrim(p_token_hash));

  if p_wallet_address !~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$' then
    raise exception 'Invalid Solana wallet address';
  end if;
  if p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Session token hash must be a SHA-256 hex digest';
  end if;
  if p_session_expires_at <= now()
     or p_session_expires_at > now() + interval '30 days' then
    raise exception 'Session expiration must be within 30 days';
  end if;

  update public.wallet_challenges
  set consumed_at = now(), attempt_count = attempt_count + 1
  where id = p_challenge_id
    and wallet_address = p_wallet_address
    and consumed_at is null
    and expires_at > now()
  returning id into consumed_id;

  if consumed_id is null then
    raise exception 'Challenge is invalid, expired, or already consumed';
  end if;

  insert into public.profiles (wallet_address)
  values (p_wallet_address)
  on conflict (wallet_address) do nothing;

  insert into public.wallet_sessions (
    token_hash, wallet_address, expires_at, revoked_at
  ) values (
    p_token_hash, p_wallet_address, p_session_expires_at, null
  );

  return jsonb_build_object(
    'wallet_address', p_wallet_address,
    'expires_at', p_session_expires_at
  );
end
$$;

create or replace function public.get_wallet_session(p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  session_wallet text;
  session_expiry timestamptz;
begin
  p_token_hash := lower(btrim(p_token_hash));
  if p_token_hash !~ '^[0-9a-f]{64}$' then return null; end if;

  update public.wallet_sessions s
  set last_seen_at = now()
  where s.token_hash = p_token_hash
    and s.revoked_at is null
    and s.expires_at > now()
  returning s.wallet_address, s.expires_at into session_wallet, session_expiry;

  if session_wallet is null then return null; end if;
  return jsonb_build_object(
    'wallet_address', session_wallet,
    'expires_at', session_expiry
  );
end
$$;

create or replace function public.revoke_wallet_session(p_token_hash text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.wallet_sessions
  set revoked_at = now()
  where token_hash = lower(btrim(p_token_hash)) and revoked_at is null;
  return found;
end
$$;

