      );
  end if;
  if not exists (select 1 from pg_constraint where conname = 'posts_counts_nonnegative') then
    alter table public.posts
      add constraint posts_counts_nonnegative check (
        like_count >= 0 and legacy_unattributed_like_count >= 0
        and verified_donation_lamports >= 0 and legacy_donation_lamports >= 0
        and comment_count >= 0
      );
  end if;
end
$$;

