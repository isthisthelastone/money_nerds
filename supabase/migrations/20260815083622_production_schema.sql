-- Money Nerds production data model.
--
-- This migration is deliberately additive. The legacy posts, post_info, comments,
-- and main_test tables and their original columns remain available for rollback,
-- while normalized columns/tables are populated from the legacy data.
--
-- Authentication is wallet-only and server mediated. Raw session tokens must never
-- be stored; the application stores only a SHA-256 hex digest in
-- public.wallet_sessions (an RLS-closed internal table) and keeps the raw token
-- in an HttpOnly cookie.

begin;

create extension if not exists pgcrypto with schema extensions;

create schema if not exists internal;
revoke all on schema internal from public, anon, authenticated;
grant usage on schema internal to service_role;

-- A fresh local Supabase database has no legacy migrations to replay. These
-- definitions mirror the production baseline and are no-ops against production.
create table if not exists public.posts (
  message text,
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  username varchar,
  image_url text,
  "walletAddress" text,
  donated_sum double precision default 0,
  donated jsonb default '{}'::jsonb,
  likes bigint default 0
);

create table if not exists public.post_info (
  created_at timestamptz not null default now(),
  liked_by text[],
  donated jsonb default '{}'::jsonb,
  id bigint generated by default as identity primary key
);

create table if not exists public.comments (
  user_id text,
  user_nickname text,
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  content text,
  post_id bigint,
  likes text[],
  image text
);

create table if not exists public.main_test (
  content text,
  created_at timestamptz not null default now(),
  user_id uuid default gen_random_uuid(),
  id bigint generated by default as identity primary key
);

-- The old unique(message) constraint rejected two unrelated posts with identical
-- text. Keep the legacy message column, but remove that accidental constraint.
alter table public.posts drop constraint if exists test_message_key;
alter table public.posts drop constraint if exists posts_message_key;

create table if not exists public.profiles (
  wallet_address text primary key,
  display_name text,
  bio text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_wallet_address_shape check (
    wallet_address ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
  ),
  constraint profiles_display_name_length check (
    display_name is null or char_length(display_name) between 1 and 80
  ),
  constraint profiles_bio_length check (
    bio is null or char_length(bio) <= 1000
  )
);

-- Create one durable profile for every syntactically valid wallet found anywhere
-- in the legacy system. Content continues to reference the profile when a wallet
-- later creates a new server-side session.
with wallet_events as (
  select btrim(p."walletAddress") as wallet_address, p.created_at as seen_at
  from public.posts p
  where btrim(coalesce(p."walletAddress", '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
  union all
  select btrim(c.user_id), c.created_at
  from public.comments c
  where btrim(coalesce(c.user_id, '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
  union all
  select btrim(l.wallet_address), pi.created_at
  from public.post_info pi
  cross join lateral unnest(coalesce(pi.liked_by, array[]::text[])) as l(wallet_address)
  where btrim(coalesce(l.wallet_address, '')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
  union all
  select btrim(d.key), p.created_at
  from public.posts p
  cross join lateral jsonb_each(
    case when jsonb_typeof(p.donated) = 'object' then p.donated else '{}'::jsonb end
  ) as d(key, value)
  where btrim(d.key) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
  union all
  select btrim(u.raw_user_meta_data ->> 'walletAddress'), u.created_at
  from auth.users u
  where btrim(coalesce(u.raw_user_meta_data ->> 'walletAddress', ''))
    ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
), wallets as (
  select wallet_address, min(seen_at) as first_seen_at, max(seen_at) as last_seen_at
  from wallet_events
  group by wallet_address
)
insert into public.profiles (wallet_address, display_name, created_at, updated_at)
select
  w.wallet_address,
  coalesce(
    (
      select nullif(btrim(p.username), '')
      from public.posts p
      where btrim(p."walletAddress") = w.wallet_address
      order by p.created_at desc, p.id desc
      limit 1
    ),
    (
      select nullif(btrim(c.user_nickname), '')
      from public.comments c
      where btrim(c.user_id) = w.wallet_address
      order by c.created_at desc, c.id desc
      limit 1
    )
  ),
  coalesce(w.first_seen_at, now()),
  coalesce(w.last_seen_at, now())
from wallets w
on conflict (wallet_address) do update
set display_name = coalesce(public.profiles.display_name, excluded.display_name),
    updated_at = greatest(public.profiles.updated_at, excluded.updated_at);

-- Retain all old fake-email auth mappings, including duplicate auth users for the
-- same wallet. New custom wallet sessions do not depend on auth.users.
create table if not exists internal.legacy_auth_wallet_links (
  auth_user_id uuid primary key references auth.users(id) on delete cascade,
  wallet_address text not null references public.profiles(wallet_address) on delete restrict,
  linked_at timestamptz not null default now()
);

insert into internal.legacy_auth_wallet_links (auth_user_id, wallet_address, linked_at)
select
  u.id,
  btrim(u.raw_user_meta_data ->> 'walletAddress'),
  coalesce(u.created_at, now())
from auth.users u
where btrim(coalesce(u.raw_user_meta_data ->> 'walletAddress', ''))
  ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$'
on conflict (auth_user_id) do update
set wallet_address = excluded.wallet_address;

-- Add normalized, strongly constrained post columns without removing the rollback
-- columns username, message, image_url, walletAddress, donated, donated_sum, likes.
alter table public.posts
  add column if not exists author_wallet text,
  add column if not exists nickname text,
  add column if not exists body text,
  add column if not exists category text default 'anything',
